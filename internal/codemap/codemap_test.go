func write(t *testing.T, root, name, content string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func project(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	write(t, root, "builtin/builtin.go", `package builtin

// Builtins lists every builtin function.
var Builtins = []*Function{
	{Name: "abs"},
}

var index = map[string]int{}
`)
	write(t, root, "builtin/function.go", "package builtin\n\ntype Function struct {\n\tName string\n}\n\nfunc (f *Function) Type() string { return \"\" }\n")
	write(t, root, "builtin/builtin_test.go", "package builtin\n\nfunc helper() {}\n\nfunc TestBuiltin(t *testing.T) {\n}\n")
	write(t, root, "optimizer/fold.go", "package optimizer\n\ntype fold struct{}\n\nfunc (f *fold) Visit(node *Node) {\n\t_ = Builtins\n}\n")
	write(t, root, "web/routes.py", "import os\n\nclass Router:\n    def resolve(self, path):\n        return path\n")
	write(t, root, "node_modules/lib/index.js", "function shouldNotAppear() {}\n")
	write(t, root, ".hidden/x.go", "package x\n\nfunc Hidden() {}\n")
	write(t, root, "gen/tables.go", "// Code generated by gen. DO NOT EDIT.\n\npackage gen\n\nfunc Generated() {}\n")
	write(t, root, "README.md", "# not code\n")
	return root
}

func TestBuildFindsDeclarations(t *testing.T) {
	m, err := Build(project(t))
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]Symbol{}
	for _, s := range m.Symbols {
		got[s.Path+"::"+s.Name] = s
	}
	for key, lines := range map[string][2]int{
		"builtin/builtin.go::Builtins":         {4, 6},
		"builtin/function.go::Function":        {3, 5},
		"builtin/function.go::Function.Type":   {7, 7},
		"builtin/builtin_test.go::TestBuiltin": {5, 6},
		"optimizer/fold.go::fold.Visit":        {5, 7},
		"web/routes.py::Router":                {3, 3},
		"web/routes.py::resolve":               {4, 4},
	} {
		s, ok := got[key]
		if !ok || s.Line != lines[0] || s.EndLine != lines[1] {
			t.Errorf("%s: got %+v (found %v), want lines %v", key, s, ok, lines)
		}
	}
	for _, key := range []string{"builtin/builtin.go::index", "builtin/builtin_test.go::helper",
		"node_modules/lib/index.js::shouldNotAppear", ".hidden/x.go::Hidden", "gen/tables.go::Generated"} {
		if _, ok := got[key]; ok {
			t.Errorf("%s should be skipped", key)
		}
	}
	if got["builtin/builtin.go::Builtins"].Doc != "Builtins lists every builtin function." || got["builtin/builtin.go::Builtins"].refs != 1 {
		t.Errorf("doc and references: %+v", got["builtin/builtin.go::Builtins"])
	}
}

func TestRenderRanksTheFolderThePromptIsAbout(t *testing.T) {
	m, _ := Build(project(t))
	out := m.Render("Add a new builtin function sign(x) like the existing builtins", 200)
	lines := strings.Split(out, "\n")
	if !strings.HasPrefix(lines[0], "builtin/") || strings.Contains(out, "web/routes.py") {
		t.Fatalf("builtin files should lead and unrelated ones stay out:\n%s", out)
	}
	if !strings.Contains(out, "builtin/builtin.go: Builtins 4-6") {
		t.Fatalf("declaration with its lines missing:\n%s", out)
	}
	fold := m.Render("make the optimizer fold constant calls", 200)
	if !strings.HasPrefix(fold, "optimizer/fold.go: ") || !strings.Contains(fold, "fold.Visit 5-7") {
		t.Fatalf("got:\n%s", fold)
	}
	if out := m.Render("the and of a", 200); out != "" {
		t.Fatalf("a prompt of stopwords matches nothing, got %q", out)
	}
}

func TestRenderRespectsBudget(t *testing.T) {
	root := t.TempDir()
	var src strings.Builder
	src.WriteString("package big\n\n")
	for i := 0; i < 50; i++ {
		src.WriteString("func Handler" + strings.Repeat("x", i%7) + string(rune('A'+i%26)) + "() {}\n")
	}
	for _, f := range []string{"a", "b", "c", "d", "e"} {
		write(t, root, "handlers/"+f+".go", src.String())
	}
	m, _ := Build(root)
	out := m.Render("handler", 60)
	if n := search.EstimateTokens(out); n > 75 {
		t.Fatalf("~%d tokens for a budget of 60:\n%s", n, out)
	}
	for _, line := range strings.Split(out, "\n") {
		if strings.Count(line, ",") >= maxPerFile {
			t.Fatalf("more than %d declarations for one file: %s", maxPerFile, line)
		}
	}
}

func TestBuildFilesAnswerBuildQuestions(t *testing.T) {
	root := project(t)
	write(t, root, "go.mod", "module x\n\ngo 1.24\n")
	write(t, root, "Makefile", "test:\n\tgo test ./...\n")
	write(t, root, ".github/workflows/ci.yml", "on: push\n")
	write(t, root, "scripts/gen.sh", "echo gen\n")
	write(t, root, "builtin/deep/go.mod", "module too/deep\n")
	m, _ := Build(root)

	out := m.Render("how is this project built", 300)
	if !strings.HasPrefix(out, "build and CI: ") {
		t.Fatalf("a build question should lead with the build files:\n%s", out)
	}
	for _, f := range []string{"go.mod", "Makefile", "scripts/", ".github/workflows/ci.yml"} {
		if !strings.Contains(out, f) {
			t.Fatalf("%s missing from the build line:\n%s", f, out)
		}
	}
	if strings.Contains(out, "builtin/deep/go.mod") {
		t.Fatalf("manifests deeper than one folder are not listed:\n%s", out)
	}
	if out := m.Render("", 300); !strings.HasPrefix(out, "build and CI: ") {
		t.Fatalf("the overview should include the build files:\n%s", out)
	}
	if out := m.Render("add a builtin function", 300); strings.Contains(out, "build and CI") {
		t.Fatalf("a code question should not get the build line:\n%s", out)
	}
}
